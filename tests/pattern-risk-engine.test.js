"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require("node:path").join(__dirname, "../trading-engine.js"), "utf8");
const context = { Date, console, Number, Math, Array, Object, String, JSON, setTimeout: () => 0 };
context.window = context;
vm.runInNewContext(source.slice(0, source.indexOf("  /* Live scalping layer.")) + "\n})(window);", context);
const E = context.TradingEngine;
assert.equal(typeof E.detectPatterns, "function");
assert.equal(typeof E.calculateTradePlan, "function");
function bar(i, o, h, l, c, v, atr=1) { return {time:i,closeTime:i+59999,open:o,high:h,low:l,close:c,volume:v,atr,volumeRatio:1}; }
let shooting = Array.from({length:40},(_,i)=>bar(i,100,101,99,100,100));
shooting.push(bar(41,100,106,99.7,100.5,110));
assert.ok(E.detectPatterns(shooting).names.includes("Shooting Star"), "recognizes Shooting Star wick/body geometry");
let hammer = Array.from({length:40},(_,i)=>bar(i,100,101,99,100,100));
hammer.push(bar(41,100.5,100.8,94,100.2,110));
assert.ok(E.detectPatterns(hammer).names.includes("Hammer"), "recognizes Hammer wick/body geometry");
let engulf = Array.from({length:40},(_,i)=>bar(i,100,101,99,100,100));
engulf.push(bar(41,101,101.2,98.8,99,100),bar(42,98.8,102,98.5,101.5,130));
assert.ok(E.detectPatterns(engulf).names.includes("Bullish Engulfing"), "recognizes bullish engulfing");
const invalid = E.detectPatterns([{open:1,high:0,low:2,close:1,volume:0}]);
assert.equal(invalid.items.length,0,"invalid OHLC data fails closed");
const plan = E.calculateTradePlan("BUY",100,2,{flag:null},{capital:1000,riskPct:.5,maxExposurePct:25,feePct:.1,slippagePct:.05},.05);
assert.ok(plan.stop < plan.entry && plan.target > plan.entry);
assert.ok(plan.qty > 0 && plan.notional <= 250.000001,"position size respects 25% exposure cap");
assert.ok(plan.riskCash <= 5.000001,"risk budget is at most 0.5% of 1,000");
assert.ok(Number.isFinite(plan.riskReward),"net reward/risk includes estimated fees, slippage and spread");
const flagPlan = E.calculateTradePlan("BUY",110,2,{flag:{breakout:true,breakoutPrice:110,poleLength:15,flagLow:106}},{capital:1000},.03);
assert.equal(flagPlan.target,125,"bullish flag target equals breakout plus measured flagpole");
assert.ok(flagPlan.stop < 110,"flag stop sits below flag support");
const sell = E.calculateTradePlan("SELL",100,2,{flag:null},{capital:1000},.05);
assert.equal(sell.qty,0,"spot sell quantity is never invented without known holdings");
console.log("OK: candlestick pattern geometry, flag target and risk sizing.");
