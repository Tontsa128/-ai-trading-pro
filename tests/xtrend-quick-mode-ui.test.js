"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const html = fs.readFileSync("public/xtrend.html", "utf8");
const ui = fs.readFileSync("public/xtrend-quick-mode-ui.js", "utf8");
const engine = fs.readFileSync("public/xtrend-quick-mode.js", "utf8");
for (const interval of ["1S", "5S", "1M", "5M"]) assert.match(html, new RegExp('data-interval="' + interval + '"'));
assert.match(html, /lightweight-charts@5\.3\.0/);
assert.match(html, /EMA 20/);
assert.match(html, /Bollinger Bands/);
assert.match(html, /RSI 14/);
assert.match(html, /MACD hist/);
assert.match(html, /AI Trade Signals & Log/);
assert.match(html, /TradingView/);
assert.doesNotMatch(html, /\b(?:demo|sample|mock)\s+(?:price|candle|quote)\b/i);
assert.match(ui, /quote\.source !== "XTREND"/, "reject non-XTrend quote source");
assert.match(ui, /bar\.source !== "XTREND"/, "reject non-XTrend candles");
assert.match(ui, /quoteAgeMs > XTrendQuickMode\.defaults\.maxQuoteAgeMs/, "reject stale quotes");
assert.match(ui, /createSeriesMarkers/, "use v5 chart markers API");
assert.match(ui, /barsForSelectedInterval/, "switch between real interval bars");
assert.match(engine, /aggregateTradeTicks/, "support real tick-to-candle aggregation");
console.log("XTrend Quick Mode UI tests passed: intervals, indicators, attribution, provenance, freshness and markers.");
